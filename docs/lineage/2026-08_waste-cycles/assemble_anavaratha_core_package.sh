#!/usr/bin/env bash
set -euo pipefail
cd /home/ubuntu/anavaratha
pkg="anavaratha_core_package"
rm -rf "$pkg"
mkdir -p "$pkg"/{00_START_HERE,01_CORE_IDENTITY,02_CONCEPTUAL_FRAMEWORKS,03_METHOD_AND_DESCENT,04_SYNTHESIZED_RESEARCH}
cp ANAVARATHA_CORE_PACKAGE_README.md "$pkg/00_START_HERE/"
cp ANAVARATHA_MASTER_RESEARCH_ARCHITECTURE_V0_1.md ANAVARATHA_THREE_DOMAIN_ARCHITECTURE_V0_1.md "$pkg/01_CORE_IDENTITY/"
cp ANAVARATHA_THERMODYNAMICS_DISSIPATION_NEGENTROPY_FRAMEWORK_V0_1.md ANAVARATHA_DIVERGENT_DIRECTIONS_ATLAS_V0_1.md "$pkg/02_CONCEPTUAL_FRAMEWORKS/"
copy_existing() {
  local dest="$1"; shift
  for src in "$@"; do
    if [[ -e "$src" ]]; then cp -f "$src" "$dest/"; else printf '%s\n' "$src" >> "$pkg/00_START_HERE/UNAVAILABLE_OR_NOT_RESTORED_FILES.txt"; fi
  done
}
copy_existing "$pkg/03_METHOD_AND_DESCENT" ANAVARATHA_TOP_DOWN_DESCENT_ARCHITECTURE.md ANAVARATHA_CONTROLLED_DESCENT_TO_LOCAL.md ANAVARATHA_LEARNING_LEVERAGE_ACTION_ARCHITECTURE_V0_1.md
copy_existing "$pkg/04_SYNTHESIZED_RESEARCH" ANAVARATHA_GENERAL_WASTE_SYSTEM.md ANAVARATHA_EAGLE_VIEW_WASTE_MODEL.md ANAVARATHA_CAPACITY_FACILITY_DIMENSIONS_V0.1.md ANAVARATHA_FACILITY_CAPACITY_REALITY_DEEP_REVIEW_V0.1.md ANAVARATHA_WESTERN_PROVINCE_FULL_CAPACITY_REALITY_REVIEW_V0_1.md ANAVARATHA_DEMO01_MIDDLE_PROCESS_EVIDENCE_REVIEW_V0_1.md
rm -f ANAVARATHA_CORE_PACKAGE_V0_1.zip
zip -qr ANAVARATHA_CORE_PACKAGE_V0_1.zip "$pkg"
printf '%s\n' '--- included files ---'
find "$pkg" -type f -printf '%P\n' | sort
printf '%s\n' '--- archive test ---'
unzip -tq ANAVARATHA_CORE_PACKAGE_V0_1.zip
printf '%s\n' 'archive_test=PASS'
ls -lh ANAVARATHA_CORE_PACKAGE_V0_1.zip
